import { registry } from "../src/BP/scripts/ponder/registry.js";
import { json, write } from "./files.mjs";
import { entityProperty as property } from "./entity-properties.mjs";

const q = name => `q.property('ponder:${name}')`;
const common = {
  color: property("int", 0xeeeeee, [0, 0xffffff]),
  alpha: property("float", 1.0, [0.0, 1.0]),
  through: property("bool", true),
};
const float = (value, min, max) => property("float", value, [min, max]);
const face = (width = 16, height = 16) => ({
  north: { uv: [width, 0], uv_size: [-width, height] },
  south: { uv: [0, 0], uv_size: [width, height] },
});
const plane = (origin = [-8, -8, 0], size = [16, 16, 0]) => ({ origin, size, uv: face() });
const cube = (origin, size) => ({ origin, size, uv: [0, 0] });
const root = { name: "root", pivot: [0, 0, 0] };
const bone = (name, cubes, extra = {}) => ({ name, parent: "root", pivot: [0, 0, 0], cubes, ...extra });
const billboard = { rotation: ["q.camera_rotation(0) - q.body_x_rotation", "q.camera_rotation(1) - q.body_y_rotation", 0] };
const palette = {
  r: `math.floor(${q("color")}/65536)/255`,
  g: `math.mod(math.floor(${q("color")}/256),256)/255`,
  b: `math.mod(${q("color")},256)/255`, a: q("alpha"),
};
const material = [{ "*": `${q("through")} ? material.through : material.depth` }];
const rc = (geometry, color = palette) => ({
  geometry: `geometry.${geometry}`, materials: material, textures: ["texture.white"],
  // "color" multiplies texture RGBA; overlay_color.a is a tint blend, NOT opacity.
  ignore_lighting: true, color,
});

export function generateEntities() {
  const icons = new Set(["textures/ui/ponder/logo", "textures/ui/ponder/pointer",
    ...["use", "attack", "scroll", "slot", "touch"].map(s => `textures/ui/ponder/icon_${s}`)]);
  for (const scene of registry.scenes) {
    icons.add(scene.iconPath);
    for (const event of scene.timeline.events) if (event.iconPath) icons.add(event.iconPath);
  }
  const iconPaths = [...icons];
  write("src/BP/scripts/ponder/generated/assets.js",
    "// Generated by tools/entities.mjs; edit scene/config sources instead.\n" +
    `export const ICON_PATHS = Object.freeze(${JSON.stringify(iconPaths, null, 2)});\n`);
  const geometries = [], animations = {}, controllers = {};
  const geometry = (id, bones, textureSize = 16) => {
    geometries.push({
      description: { identifier: `geometry.ponder.${id}`, texture_width: textureSize, texture_height: textureSize,
        visible_bounds_width: 64, visible_bounds_height: 64, visible_bounds_offset: [0, 0, 0] },
      bones: [root, ...bones],
    });
    return `geometry.ponder.${id}`;
  };
  const save = (type, props, clientGeometry, textures, animation, renderControllers) => {
    json(`src/BP/entities/ponder_${type}.json`, {
      format_version: "1.21.0",
      "minecraft:entity": {
        description: { identifier: `ponder:${type}`, is_spawnable: false, is_summonable: true,
          properties: Object.fromEntries(Object.entries({ ...common, ...props }).map(([k, v]) => [`ponder:${k}`, v])) },
        components: {
          "minecraft:type_family": { family: ["ponder_annotation", "inanimate"] },
          "minecraft:collision_box": { width: 0, height: 0 },
          "minecraft:physics": { has_gravity: false, has_collision: false },
          "minecraft:pushable": { is_pushable: false, is_pushable_by_piston: false },
          "minecraft:damage_sensor": { triggers: [{ cause: "all", deals_damage: "no" }] },
          "minecraft:fire_immune": {},
          "minecraft:persistent": {},
          "minecraft:conditional_bandwidth_optimization": {
            default_values: { max_optimized_distance: 0, max_dropped_ticks: 0 },
          },
        },
      },
    });
    animations[`animation.ponder.${type}`] = { loop: true, bones: animation };
    json(`src/RP/entity/ponder_${type}.entity.json`, {
      format_version: "1.10.0",
      "minecraft:client_entity": { description: {
        identifier: `ponder:${type}`,
        materials: { depth: "ponder_depth", through: "ponder_through" },
        textures: { white: "textures/ui/ponder/white", ...textures }, geometry: clientGeometry,
        animations: { update: `animation.ponder.${type}` }, scripts: { animate: ["update"] },
        render_controllers: renderControllers,
      } },
    });
  };
  const textProps = { scale: float(.055, .02, .1) }, textGeometry = {}, textAnimation = {
    root: { ...billboard, scale: `8 * ${q("scale")}` },
  }, textControllers = [];
  const pages = Object.fromEntries(Array.from({ length: 256 }, (_, page) => {
    const hex = page.toString(16).toUpperCase().padStart(2, "0");
    return [`page_${hex}`, `font/glyph_${hex}`];
  }));
  for (let i = 0; i < 8; i++) {
    textProps[`g${i}`] = property("int", -1, [-1, 16777215]);
    textProps[`p${i}`] = float(0.0, 0.0, 65535.0);
    const packed = q(`g${i}`), pos = q(`p${i}`);
    const code = `math.mod(math.max(0,${packed}),65536)`;
    const left = `math.mod(math.floor(math.max(0,${packed})/65536),16)`;
    const width = `(math.floor(math.max(0,${packed})/1048576)+1)`;
    textGeometry[`slot${i}`] = geometry(`text_${i}`, [bone(`glyph${i}`, [plane([0, -16, 0])])], 256);
    textAnimation[`glyph${i}`] = {
      position: [`2*math.mod(${pos},512)`, `-2*math.floor(${pos}/512)`, 0],
      scale: [`${packed}<0?0:${width}/16`, 1, 1],
    };
    const name = `controller.render.ponder.text_${i}`;
    controllers[name] = {
      ...rc(`slot${i}`),
      arrays: { textures: { "array.pages": Object.keys(pages).map(key => "texture." + key) } },
      textures: [`array.pages[math.floor(${code}/256)]`],
      // UVs in the base geometry cover one cell; offset selects its row/column.
      uv_anim: {
        offset: [`(math.mod(${code},16)*16+${left})/256`, `math.floor(math.mod(${code},256)/16)/16`],
        scale: [`${width}/16`, 1],
      },
      part_visibility: [{ "*": `${packed}>=0 && ${q("alpha")}>0` }],
    };
    textControllers.push(name);
  }
  save("text", textProps, textGeometry, pages, textAnimation, textControllers);

  const frameGeometry = {
    fill: geometry("frame_fill", [bone("fill", [plane()])]),
    border: geometry("frame_border", ["top", "bottom", "left", "right"].map(n => bone(n, [plane()]))),
  };
  const w = q("width"), h = q("height");
  controllers["controller.render.ponder.frame_fill"] = rc("fill", { r: 0, g: 0, b: 0, a: `${q("alpha")}*.72` });
  controllers["controller.render.ponder.frame_border"] = rc("border", { ...palette, a: `${q("alpha")}*.55` });
  save("frame", { width: float(1.0, .1, 24.0), height: float(1.0, .1, 16.0) }, frameGeometry, {}, {
    root: billboard, fill: { scale: [w, h, 1] },
    top: { position: [0, `${h}*8`, -.12], scale: [w, .025, 1] },
    bottom: { position: [0, `-${h}*8`, -.12], scale: [w, .025, 1] },
    left: { position: [`-${w}*8`, 0, -.12], scale: [.025, h, 1] },
    right: { position: [`${w}*8`, 0, -.12], scale: [.025, h, 1] },
  }, ["controller.render.ponder.frame_fill", "controller.render.ponder.frame_border"]);

  const lineGeometry = {
    edge: geometry("line_edge", [bone("edge", [cube([-8, -8, 0], [16, 16, 16])])]),
    core: geometry("line_core", [bone("core", [cube([-8, -8, -.02], [16, 16, 16.04])])]),
  };
  controllers["controller.render.ponder.line_edge"] = rc("edge", { r: .045, g: .045, b: .07, a: `${q("alpha")}*.85` });
  controllers["controller.render.ponder.line_core"] = rc("core");
  save("line", { width: float(.022, .001, .2), length: float(1.0, .001, 128.0),
    pitch: float(0.0, -180.0, 180.0), yaw: float(0.0, -360.0, 360.0) }, lineGeometry, {}, {
    root: { rotation: [q("pitch"), q("yaw"), 0] },
    edge: { scale: [`${w}*1.8`, `${w}*1.8`, q("length")] },
    core: { scale: [w, w, q("length")] },
  }, ["controller.render.ponder.line_edge", "controller.render.ponder.line_core"]);
  controllers["controller.render.ponder.icon"] = {
    ...rc("default", { r: 1, g: 1, b: 1, a: q("alpha") }),
    arrays: { textures: { "array.icons": iconPaths.map((_, i) => `texture.icon${i}`) } },
    textures: [`array.icons[${q("icon")}]`],
  };
  save("icon", { icon: property("int", 0, [0, iconPaths.length - 1]), size: float(1.0, .01, 4.0),
    angle: float(0.0, -360.0, 360.0) }, { default: geometry("icon", [bone("icon", [plane()])]) },
  Object.fromEntries(iconPaths.map((p, i) => [`icon${i}`, p])), {
    root: billboard, icon: { rotation: [0, 0, q("angle")], scale: q("size") },
  }, ["controller.render.ponder.icon"]);
  json("src/RP/models/entity/ponder.geo.json", { format_version: "1.12.0", "minecraft:geometry": geometries });
  json("src/RP/animations/ponder.animation.json", { format_version: "1.8.0", animations });
  json("src/RP/render_controllers/ponder.render_controllers.json", { format_version: "1.10.0", render_controllers: controllers });
  json("src/RP/materials/entity.material", {
    materials: { version: "1.0.0",
      "ponder_depth:entity_alphablend": { "+states": ["DisableCulling", "DisableDepthWrite"] },
      "ponder_through:ponder_depth": { "+states": ["DisableDepthTest"], depthFunc: "Always" },
    },
  });
}
